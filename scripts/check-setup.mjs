// Run after pnpm build with PLAYWRIGHT_MODULE and CHROMIUM_BIN pointing to installed browser tools.
import assert from 'node:assert/strict';
import { mkdtemp, writeFile, readFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { createServer } from 'node:net';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE ?? 'playwright');
const exec = promisify(execFile);
const cwd = resolve(fileURLToPath(new URL('../', import.meta.url)));
const root = await mkdtemp(join(tmpdir(), 'cl-setup-browser-'));
const unit = `contextlanes-setup-browser-${process.pid}`;
const project = `setup-${process.pid}`;
const port = await new Promise((resolve, reject) => { const s = createServer(); s.on('error', reject); s.listen(0, '127.0.0.1', () => { const p = s.address().port; s.close(() => resolve(p)); }); });
const url = `http://localhost:${port}`;
const run = (cmd, args, opts = {}) => exec(cmd, args, { cwd, ...opts });
const until = async (fn) => { let last; for (let i = 0; i < 150; i++) { try { return await fn(); } catch (error) { last = error; await new Promise((r) => setTimeout(r, 100)); } } throw last; };
const json = async (path, body) => { const r = await fetch(url + path, body ? { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify(body) } : {}); assert(r.ok, await r.clone().text()); return r.json(); };
let browser, lane;
try {
  const repo = join(root, 'repo');
  await run('git', ['init', '-b', 'main', repo]);
  await run('git', ['-c', 'user.name=ContextLanes', '-c', 'user.email=test@example.invalid', 'commit', '--allow-empty', '-m', 'Fixture'], { cwd: repo });
  const loader = createRequire(join(cwd, 'package.json')).resolve('tsx');
  const config = join(root, 'config.toml');
  // Only fixture paths and an SDK fake agent are seeded. Ownership and projects start empty.
  await writeFile(config, `[listen]\nport=${port}\n[paths]\ndata=${JSON.stringify(join(root, 'data'))}\nlanes=${JSON.stringify(join(root, 'lanes'))}\n[agents.claude-code]\ncommand=${JSON.stringify(process.execPath)}\nargs=${JSON.stringify(['--import', loader, '--conditions=source', join(cwd, 'apps/lanehost/test/fixtures/fake-stdio.ts')])}\n`);
  await run('systemd-run', ['--user', `--unit=${unit}`, '--collect', `--working-directory=${cwd}`, `--setenv=CONTEXTLANES_CONFIG=${config}`, process.execPath, 'apps/daemon/dist/main.js']);
  await until(() => json('/api/health'));
  assert.equal((await fetch(url + '/api/projects')).status, 401);
  const cli = await run(process.execPath, ['apps/cli/dist/main.js', 'setup'], { env: { ...process.env, CONTEXTLANES_URL: url } });
  const code = await readFile(join(root, 'data/claim-code'), 'utf8');
  assert(cli.stdout.includes(code)); assert(cli.stdout.includes(url + '/setup'));
  browser = await chromium.launch({ headless: true, executablePath: process.env.CHROMIUM_BIN, args: ['--no-sandbox'] });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const page = await context.newPage();
  const errors = []; page.on('pageerror', (e) => errors.push(e.message));
  const cdp = await context.newCDPSession(page);
  await cdp.send('WebAuthn.enable');
  const { authenticatorId } = await cdp.send('WebAuthn.addVirtualAuthenticator', { options: { protocol: 'ctap2', transport: 'internal', hasResidentKey: true, hasUserVerification: true, isUserVerified: true, automaticPresenceSimulation: true } });
  await page.goto(url);
  await page.getByRole('heading', { name: 'Claim this machine', exact: true }).waitFor();
  await page.getByLabel('Claim code', { exact: true }).fill(code);
  let registration;
  page.on('request', (r) => { if (r.url().endsWith('/api/setup/claim/passkey')) registration = r.postDataJSON(); });
  await page.getByRole('button', { name: 'Claim with a passkey' }).click();
  await page.getByRole('heading', { name: 'Remote access', exact: true }).first().waitFor();
  assert((await readFile(config, 'utf8')).includes('[access.passkey]'));
  assert.equal((await fetch(url + '/api/setup/claim/passkey', { method: 'POST', headers: { host: `localhost:${port}`, origin: url, 'content-type': 'application/json' }, body: JSON.stringify(registration) })).status, 409);
  await page.getByRole('button', { name: 'Continue', exact: true }).click();
  await page.getByRole('heading', { name: 'Connect agents', exact: true }).waitFor();
  await page.getByText('Adapter found', { exact: false }).first().waitFor();
  await page.getByRole('button', { name: 'Continue', exact: true }).click();
  await page.getByLabel('Repository path').fill(repo); await page.getByLabel('Project name (optional)').fill(project);
  await page.getByRole('button', { name: 'Add project', exact: true }).click();
  await page.getByText(project, { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Continue', exact: true }).click();
  await page.getByRole('button', { name: 'Generate Web Push keys' }).click();
  await page.getByLabel('Push contact').fill('mailto:test@example.invalid');
  await page.getByRole('button', { name: 'Save notifications', exact: true }).click();
  await page.getByText('Notifications saved.', { exact: true }).waitFor();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: '/tmp/contextlanes-setup-phone.png', fullPage: true });
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.getByRole('button', { name: 'Continue', exact: true }).click();
  await page.getByRole('heading', { name: 'Local models', exact: true }).first().waitFor();
  await page.getByRole('button', { name: 'Continue', exact: true }).click();
  await page.getByLabel('Task', { exact: true }).fill('permission');
  await page.getByRole('button', { name: 'Start lane', exact: true }).click();
  await page.getByRole('button', { name: 'Allow once', exact: true }).waitFor();
  lane = (await json(`/api/projects/${project}/lanes`))[0];
  await page.getByRole('button', { name: 'Allow once', exact: true }).click();
  await until(async () => assert((await json(`/api/lanes/${lane.id}/events`)).some((e) => e.type === 'agent.message' && e.payload.text.includes('Finished permission'))));
  await page.goto(url + '/settings');
  await page.getByRole('heading', { name: 'Settings', exact: true }).waitFor();
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.screenshot({ path: '/tmp/contextlanes-setup-settings-desktop.png', fullPage: true });
  // Require owner sessions now, then restart to verify persisted registration, project and cookie.
  let toml = await readFile(config, 'utf8'); toml = toml.replace('allowLocal = true', 'allowLocal = false'); await writeFile(config, toml);
  const restartStarted = Date.now();
  await run('systemctl', ['--user', 'restart', unit]); assert(Date.now() - restartStarted < 10000, 'Live browser delayed daemon restart'); await until(() => json('/api/health'));
  await page.reload(); await page.getByRole('heading', { name: 'Settings', exact: true }).waitFor();
  assert.equal((await fetch(url + '/api/projects')).status, 401);
  await context.clearCookies();
  await page.goto(url + '/setup'); await page.getByRole('heading', { name: 'Sign in', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Sign in with a passkey' }).click();
  await page.getByRole('heading', { name: 'Remote access', exact: true }).first().waitFor();
  await context.clearCookies(); await page.reload();
  await page.getByRole('heading', { name: 'Sign in', exact: true }).waitFor();
  await cdp.send('WebAuthn.setUserVerified', { authenticatorId, isUserVerified: false });
  await page.getByRole('button', { name: 'Sign in with a passkey' }).click();
  await page.getByRole('alert').waitFor({ timeout: 65000 });
  assert.equal((await page.request.get(url + '/api/projects')).status(), 401);
  assert.deepEqual(errors, []);
  console.log('PASS: fresh owner claim with real WebAuthn verification, replay denial, wizard project/notifications, SDK fake first lane + permission, phone layout, config/service restart, persisted session and passkey sign-in, UV failure denied.');
} finally {
  await browser?.close();
  if (lane) { await run('systemctl', ['--user', 'stop', `contextlanes-lane-${lane.id.replace('/', '-')}`]).catch(() => {}); await run('tmux', ['kill-session', '-t', lane.terminal]).catch(() => {}); }
  await run('systemctl', ['--user', 'stop', unit]).catch(() => {});
  await rm(root, { recursive: true, force: true });
}
